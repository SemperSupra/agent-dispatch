func TestBootKeyboardSixSlotAndLED(t *testing.T){
 s,e:=Decode(boot);if e!=nil{t.Fatal(e)}
 if s.ModifierBits!=8||s.BootArraySlots!=6||s.LEDBits!=5||s.NKROBits!=0{
  t.Fatalf("wrong boot summary %+v",s)
 }
 if len(s.ReportIDs)!=1||s.ReportIDs[0]!=0{t.Fatal("wrong implicit report ID")}
 if s.PhysicalKeyCountKnown || s.KeyboardLocaleKnown{t.Fatal("HID descriptor misrepresented physical keyboard")}
}
func TestNKROReportIDNotPhysicalKeyCount(t *testing.T){
 s,e:=Decode(nkro);if e!=nil{t.Fatal(e)}
 if s.NKROBits!=112||s.BootArraySlots!=0||len(s.ReportIDs)!=1||s.ReportIDs[0]!=1{
  t.Fatalf("wrong NKRO interpretation %+v",s)
 }
 if s.PhysicalKeyCountKnown{t.Fatal("bitmap size equals NOT physical key count")}
}
func TestMalformedAndHostileFieldsFailClosed(t *testing.T){
 invalid:=[][]byte{
  nil,{0xfe,0x01,0x00,0x00},boot[:len(boot)-2],
  {0x05,0x07,0xa1,0x01,0x75,0x01,0x95,0x00,0x81,0x02,0xc0},
  {0x05,0x07,0xa1,0x01,0x75,0x20,0x96,0xff,0xff,0x81,0x02,0xc0},
  {0xb4,0xa1,0x01,0xc0},
 }
 for i,b:=range invalid{
  if _,e:=Decode(b);!errors.Is(e,ErrMalformed){t.Fatalf("fixture %d unexpectedly accepted: %v",i,e)}
 }
}
func TestNonUSUsageNotKeyboardLocale(t *testing.T){
 desc:=[]byte{0x05,0x01,0x09,0x06,0xa1,0x01,
  0x05,0x07,0x19,0x64,0x29,0x91,0x15,0x00,0x25,0x01,
  0x75,0x01,0x95,0x2e,0x81,0x02,0xc0}
 s,e:=Decode(desc);if e!=nil{t.Fatal(e)}
 if s.NKROBits!=46||s.KeyboardLocaleKnown{t.Fatalf("non US usage implied layout: %+v",s)}
}
